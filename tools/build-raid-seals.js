#!/usr/bin/env node
/* ============================================================
   Writes assets/raid-seals.js: each raid/dungeon guide's seal (the
   seal in Bungie's current Titles list with the activity's name, e.g.
   King's Fall → Kingslayer), for "Your clears" on the guide pages
   (assets/your-clears.js), which reads the seal's progress from the
   player's public profile (component 700) with no other download.
   Activities without a seal of their own name (Pit of Heresy, Prophecy,
   Grasp of Avarice, Shattered Throne) get none.

   Run after adding a raid or dungeon, or when Bungie adds its seal:
   node tools/build-raid-seals.js   (needs network)
   ============================================================ */
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const window = {};
new Function("window", fs.readFileSync(path.join(ROOT, "assets/activity-index.js"), "utf8"))(window);
const key = (fs.readFileSync(path.join(ROOT, "assets/api-keys.js"), "utf8").match(/BUNGIE_API_KEY:\s*"([0-9a-f]+)"/) || [])[1];
const fold = s => s.toLowerCase().replace(/^the /, "").replace(/[’']/g, "'");
const TITLES_ROOT = 616318467; // DestinyRecordDefinition's seals root (profileRecords.recordSealsRootNodeHash)

(async () => {
  const headers = { "X-API-Key": key, Origin: "https://coopgg.github.io" };
  const manifest = (await (await fetch("https://www.bungie.net/Platform/Destiny2/Manifest/", { headers })).json()).Response;
  const paths = manifest.jsonWorldComponentContentPaths.en;
  const [nodes, recs] = await Promise.all([paths.DestinyPresentationNodeDefinition, paths.DestinyRecordDefinition].map(async p => (await fetch("https://www.bungie.net" + p)).json()));
  const seals = (nodes[TITLES_ROOT].children.presentationNodes || []).map(c => c.presentationNodeHash);
  const all = [].concat(window.ActivityIndex.raids, window.ActivityIndex.dungeons);
  const out = {};
  for (const a of all){
    const h = seals.find(s => fold(nodes[s].displayProperties.name) === fold(a.name));
    if (!h) continue;
    const n = nodes[h], rec = recs[n.completionRecordHash] || {}, ti = rec.titleInfo || {};
    out[a.slug] = { node: h, title: (ti.titlesByGender && (ti.titlesByGender.Male || Object.values(ti.titlesByGender)[0])) || n.displayProperties.name, icon: n.displayProperties.icon || "" };
  }
  const body = "/* GENERATED by tools/build-raid-seals.js from Bungie's presentation nodes\n" +
    "   (manifest " + manifest.version + "). Don't edit; re-run it.\n" +
    "   guide slug -> { node: seal presentation node hash, title, icon } */\n" +
    "window.RaidSeals = " + JSON.stringify(out).replace(/\},"/g, '},\n"') + ";\n";
  fs.writeFileSync(path.join(ROOT, "assets/raid-seals.js"), body);
  console.log(Object.keys(out).length + " of " + all.length + " guides have a seal; none: " + all.filter(a => !out[a.slug]).map(a => a.name).join(", "));
})();
