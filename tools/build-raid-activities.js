#!/usr/bin/env node
/* ============================================================
   Writes assets/raid-activities.js: every raid and dungeon activity
   hash in Bungie's DestinyActivityDefinition, matched to our guides
   (assets/activity-index.js) by name, for the Raid & Dungeon Report
   (report.html). Activities with no guide of ours (Leviathan, Crown of
   Sorrow…) keep their own name and slug null.

   Run after adding a raid or dungeon (or when Bungie adds a new
   version of one): node tools/build-raid-activities.js
   Needs network; uses the dev API key from assets/api-keys.js.
   ============================================================ */
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const RAID_TYPE = 2043403989, DUNGEON_TYPE = 608898761;

function load(file, name){
  const window = {};
  new Function("window", fs.readFileSync(path.join(ROOT, file), "utf8"))(window);
  return window[name];
}
const key = (fs.readFileSync(path.join(ROOT, "assets/api-keys.js"), "utf8").match(/BUNGIE_API_KEY:\s*"([0-9a-f]+)"/) || [])[1];
const fold = s => s.toLowerCase().replace(/^the /, "").replace(/[’']/g, "'");

// "King's Fall: Master" -> base "King's Fall", version "Master";
// "The Desert Perpetual (Epic): Contest" -> "The Desert Perpetual", "Epic Contest";
// "Featured Encore: Warpriest: The Pantheon" -> Pantheon.
function split(name){
  // Pantheon's bosses run as "Featured Encore/Reprise: <boss>: …" too.
  if (/pantheon|^featured (encore|reprise)|atraks sovereign/i.test(name)) return { base: "Pantheon", version: "" };
  const [head, ...rest] = name.split(": ");
  const epic = /\s*\(epic\)/i.test(head);
  return { base: head.replace(/\s*\(epic\)/i, "").trim(), version: ((epic ? "Epic " : "") + rest.join(": ")).trim() };
}
// Bungie's many labels for the plain version all read "Normal" in the report.
const versionLabel = v => !v || /^(standard|normal)$/i.test(v) ? "Normal" : v.replace(/^Epic Standard$/i, "Epic").replace(/\s*\(Matchmade\)/i, " (matchmade)");

(async () => {
  const index = load("assets/activity-index.js", "ActivityIndex");
  const ours = [].concat(index.raids.map(r => [r, "raid"]), index.dungeons.map(d => [d, "dungeon"]));
  const headers = { "X-API-Key": key, Origin: "https://coopgg.github.io" };
  const manifest = (await (await fetch("https://www.bungie.net/Platform/Destiny2/Manifest/", { headers })).json()).Response;
  const defs = await (await fetch("https://www.bungie.net" + manifest.jsonWorldComponentContentPaths.en.DestinyActivityDefinition)).json();
  const out = {}, unmatched = new Set();
  for (const h in defs){
    const a = defs[h], name = (a.displayProperties || {}).name;
    if (!name || (a.activityTypeHash !== RAID_TYPE && a.activityTypeHash !== DUNGEON_TYPE)) continue;
    const { base, version } = split(name);
    const hit = ours.find(([x]) => fold(x.name) === fold(base));
    if (!hit) unmatched.add(base);
    // [slug or null, kind, version label, name when there's no guide]
    out[h] = hit ? [hit[0].slug, hit[1], versionLabel(version)] : [null, a.activityTypeHash === RAID_TYPE ? "raid" : "dungeon", versionLabel(version), base];
  }
  const body = "/* GENERATED by tools/build-raid-activities.js from Bungie's DestinyActivityDefinition\n" +
    "   (manifest " + manifest.version + "). Don't edit; re-run it.\n" +
    "   hash -> [guide slug or null, \"raid\" | \"dungeon\", version label, name (only when no guide)] */\n" +
    "window.RaidActivities = " + JSON.stringify(out).replace(/\],"/g, '],\n"') + ";\n";
  fs.writeFileSync(path.join(ROOT, "assets/raid-activities.js"), body);
  const covered = new Set(Object.values(out).map(v => v[0]).filter(Boolean));
  console.log(Object.keys(out).length + " activities; guides covered: " + covered.size + "/" + ours.length + "; no guide: " + [...unmatched].join(", "));
  const missing = ours.filter(([x]) => !covered.has(x.slug)).map(([x]) => x.name);
  if (missing.length){ console.error("No activity found for: " + missing.join(", ")); process.exit(1); }
})();
