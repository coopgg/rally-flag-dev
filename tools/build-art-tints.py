#!/usr/bin/env python3
"""Writes assets/art-tints.js: each piece of activity art's average colour,
shown behind the image while it loads (rallyFlagArtThumb / rallyFlagArtTint
in nav.js), so a card or guide header looks finished on a slow connection.

Finds the art the site uses: Bungie paths ("/img/....jpg|png") in assets/*.js
and the hand-written pages, the PvP playlists' ART("name") in assets/pvp.js,
and our own key art in assets/art/*.jpg. Downloads each once, shrinks it and
averages it (a touch darker, so light text never sits on a bright tint).

Run after adding a raid, dungeon or other art (needs network and Pillow):
  python3 tools/build-art-tints.py           # write
  python3 tools/build-art-tints.py --check   # exit 1 if art is missing a tint
"""
import io, json, os, re, sys, urllib.request
from PIL import Image, ImageStat

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "assets", "art-tints.js")
GENERATED = re.compile(r"^(raid|dungeon)-(?!guide\.html$).+\.html$")  # built guides repeat the data files' art


def art_paths():
    found = set()
    files = [os.path.join("assets", f) for f in os.listdir(os.path.join(ROOT, "assets")) if f.endswith(".js") and f != "art-tints.js"]
    files += [f for f in os.listdir(ROOT) if f.endswith(".html") and not GENERATED.match(f)]
    for rel in files:
        text = open(os.path.join(ROOT, rel), encoding="utf-8").read()
        found.update(re.findall(r'"(/img/[^"\s]+\.(?:jpg|png))"', text))
        if rel.endswith("pvp.js"):
            found.update("/img/destiny_content/pgcr/" + n + ".jpg" for n in re.findall(r'ART\("([a-z0-9_]+)"\)', text))
    for f in os.listdir(os.path.join(ROOT, "assets", "art")):
        if f.endswith(".jpg"):
            found.add("assets/art/" + f)
    # Activity art only (pgcr images and our key art), not item icons or overlays.
    return sorted(p for p in found if (p.startswith("/img/destiny_content/pgcr/") or p.startswith("assets/art/")) and "placeholder" not in p)


def tint(path):
    if path.startswith("assets/"):
        data = open(os.path.join(ROOT, path), "rb").read()
    else:
        req = urllib.request.Request("https://www.bungie.net" + path, headers={"User-Agent": "RallyFlag-art-tints (+https://rallyflag.gg)"})
        data = urllib.request.urlopen(req, timeout=30).read()
    im = Image.open(io.BytesIO(data)).convert("RGB").resize((16, 9), Image.BILINEAR)
    r, g, b = ImageStat.Stat(im).mean
    return "#%02x%02x%02x" % tuple(int(v * 0.85) for v in (r, g, b))


def main():
    paths = art_paths()
    old = {}
    if os.path.exists(OUT):
        m = re.search(r"=\s*(\{.*\});", open(OUT, encoding="utf-8").read(), re.S)
        old = json.loads(m.group(1)) if m else {}
    if "--check" in sys.argv:
        missing = [p for p in paths if p not in old]
        if missing:
            print("art without a tint (run tools/build-art-tints.py):", ", ".join(missing))
            sys.exit(1)
        print("all %d pieces of art have a tint" % len(paths))
        return
    tints = {}
    for p in paths:
        try:
            tints[p] = tint(p)
        except Exception as e:  # keep the old colour if one download fails
            print("skipped", p, "-", e)
            if p in old:
                tints[p] = old[p]
    body = ("/* GENERATED by tools/build-art-tints.py: the average colour of each piece of\n"
            "   art, shown behind it while it loads. Don't edit; re-run it. */\n"
            "window.RallyFlagArtTints = " + json.dumps(tints, indent=0, sort_keys=True).replace('",\n', '", ') + ";\n")
    open(OUT, "w", encoding="utf-8").write(body)
    print("%d tints written to assets/art-tints.js" % len(tints))


if __name__ == "__main__":
    main()
