#!/usr/bin/env node
/* ============================================================
   Generates one static page per raid and dungeon
   (raid-<slug>.html, dungeon-<slug>.html) from the guide templates
   (raid-guide.html, dungeon-guide.html) and the data files.

   Why: link previews (Discord, iMessage, X…) never run JavaScript, so a
   single raid-guide.html?slug=… page can only ever preview as the generic
   "Raid Guide". Each generated page carries that activity's own <title>,
   description, canonical URL and Open Graph / Twitter tags (official art
   as the image), and sets window.GUIDE_SLUG so the template's script
   renders it. Everything else is the template, byte for byte.

   Also writes assets/activity-index.js: a small summary of every raid and
   dungeon (name, slug, art, difficulties, armor sets, encounter count) for
   the pages that only list them (Home, This Week, Raids, Dungeons), so
   they don't download the full guide text (~180KB).

   Run after editing a guide template or raids-data.js / dungeons-data.js:
     node tools/build-guide-pages.js           write the pages
     node tools/build-guide-pages.js --check   exit 1 if any page is stale
   No dependencies; Node 18+.
   ============================================================ */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");
const SITE = "https://rallyflag.gg/";
const CHECK = process.argv.includes("--check");

function loadData(file, globalName){
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, "assets", file), "utf8"), sandbox, { filename: file });
  return sandbox.window[globalName];
}

const esc = s => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// Previews show ~200 characters; cut at a word boundary.
function describe(item, kindLabel){
  const text = (item.summary || "").replace(/\s+/g, " ").trim();
  if (!text) return "Everything you need for the " + item.name + " " + kindLabel.toLowerCase() + " in Destiny 2: encounters, armor set bonuses and puzzle solvers.";
  if (text.length <= 200) return text;
  return text.slice(0, 197).replace(/\s+\S*$/, "") + "…";
}

// Bungie art paths start with "/"; anything else is a file on this site.
const artUrl = art => !art ? SITE + "assets/og-image.png" : art.charAt(0) === "/" ? "https://www.bungie.net" + art : SITE + art;

// Replace exactly one occurrence, so a template change that breaks the
// pattern fails loudly instead of producing a page with generic tags.
function replaceOnce(html, pattern, replacement, label){
  const matches = html.match(new RegExp(pattern.source, "g"));
  if (!matches || matches.length !== 1) throw new Error(label + ": expected 1 match in template, found " + (matches ? matches.length : 0));
  return html.replace(pattern, replacement);
}

function buildPage(template, kind, kindLabel, item){
  const file = kind + "-" + item.slug + ".html";
  const url = SITE + file;
  const title = item.name + " " + kindLabel + " Guide";
  const desc = describe(item, kindLabel);
  const image = item.art ? artUrl(item.art) : artUrl(null);
  const imageAlt = item.art ? item.name + ", official Destiny 2 art" : "Rally Flag: Destiny 2 raid and dungeon guides, weapon god rolls, builds and live trackers";
  const [w, h] = item.art ? [1280, 720] : [1200, 630];

  let html = template;
  html = replaceOnce(html, /<!DOCTYPE html>\n/, "<!DOCTYPE html>\n<!-- GENERATED by tools/build-guide-pages.js from " + kind + "-guide.html and assets/" + kind + "s-data.js. Don't edit; edit those and re-run. -->\n", "doctype");
  html = replaceOnce(html, /<title>[^<]*<\/title>/, "<title>" + esc(title) + " - Rally Flag</title>\n<script>window.GUIDE_SLUG = " + JSON.stringify(item.slug) + ";</script>", "title");
  html = replaceOnce(html, /<meta name="description" content="[^"]*">/, '<meta name="description" content="' + esc(desc) + '">', "description");
  html = replaceOnce(html, /<meta property="og:title" content="[^"]*">/, '<meta property="og:title" content="' + esc(title) + '">', "og:title");
  html = replaceOnce(html, /<meta property="og:description" content="[^"]*">/, '<meta property="og:description" content="' + esc(desc) + '">', "og:description");
  html = replaceOnce(html, /<meta property="og:url" content="[^"]*">/, '<meta property="og:url" content="' + url + '">\n<link rel="canonical" href="' + url + '">', "og:url");
  html = replaceOnce(html, /<meta property="og:image" content="[^"]*">/, '<meta property="og:image" content="' + esc(image) + '">', "og:image");
  html = replaceOnce(html, /<meta property="og:image:width" content="[^"]*">/, '<meta property="og:image:width" content="' + w + '">', "og:image:width");
  html = replaceOnce(html, /<meta property="og:image:height" content="[^"]*">/, '<meta property="og:image:height" content="' + h + '">', "og:image:height");
  html = replaceOnce(html, /<meta property="og:image:alt" content="[^"]*">/, '<meta property="og:image:alt" content="' + esc(imageAlt) + '">', "og:image:alt");
  html = replaceOnce(html, /<meta name="twitter:title" content="[^"]*">/, '<meta name="twitter:title" content="' + esc(title) + '">', "twitter:title");
  html = replaceOnce(html, /<meta name="twitter:description" content="[^"]*">/, '<meta name="twitter:description" content="' + esc(desc) + '">', "twitter:description");
  html = replaceOnce(html, /<meta name="twitter:image" content="[^"]*">/, '<meta name="twitter:image" content="' + esc(image) + '">', "twitter:image");
  // The name is in the page before any script runs (search engines, no-JS).
  html = replaceOnce(html, new RegExp('(<h1 class="title" id="' + kind + '-title">)…(</h1>)'), "$1" + esc(item.name) + "$2", "h1");
  return { file, html };
}

const sets = [
  ["raid", "Raid", loadData("raids-data.js", "RaidsData").RAIDS],
  ["dungeon", "Dungeon", loadData("dungeons-data.js", "DungeonsData").DUNGEONS]
];

let stale = 0, written = 0;
const expected = new Set();
for (const [kind, kindLabel, items] of sets){
  const template = fs.readFileSync(path.join(ROOT, kind + "-guide.html"), "utf8");
  for (const item of items){
    const { file, html } = buildPage(template, kind, kindLabel, item);
    expected.add(file);
    const target = path.join(ROOT, file);
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
    if (current === html) continue;
    if (CHECK){ console.error("stale: " + file); stale++; }
    else { fs.writeFileSync(target, html); written++; }
  }
}

// The summary file for listing pages.
{
  const summarize = item => {
    const out = { name: item.name, slug: item.slug };
    if (item.art) out.art = item.art;
    if (item.difficulties) out.difficulties = item.difficulties;
    out.armorSlugs = item.armorSlugs || [];
    out.encounterCount = (item.encounters || []).length;
    return out;
  };
  const list = items => "[\n" + items.map(i => "    " + JSON.stringify(summarize(i))).join(",\n") + "\n  ]";
  const js = "/* GENERATED by tools/build-guide-pages.js from assets/raids-data.js and\n" +
    "   assets/dungeons-data.js. Don't edit; edit those and re-run.\n" +
    "   Every raid and dungeon in summary form for pages that only list them\n" +
    "   (Home, This Week, Raids, Dungeons); the guide pages load the full data. */\n" +
    "window.ActivityIndex = {\n  raids: " + list(sets[0][2]) + ",\n  dungeons: " + list(sets[1][2]) + "\n};\n";
  const file = "assets/activity-index.js";
  expected.add(file);
  const target = path.join(ROOT, file);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  if (current !== js){
    if (CHECK){ console.error("stale: " + file); stale++; }
    else { fs.writeFileSync(target, js); written++; }
  }
}

// A page whose raid/dungeon was removed or renamed from the data.
for (const f of fs.readdirSync(ROOT)){
  if (!/^(raid|dungeon)-(?!guide\.html$).+\.html$/.test(f) || expected.has(f)) continue;
  if (!fs.readFileSync(path.join(ROOT, f), "utf8").includes("GENERATED by tools/build-guide-pages.js")) continue;
  if (CHECK){ console.error("orphaned: " + f); stale++; }
  else { fs.unlinkSync(path.join(ROOT, f)); console.log("removed " + f); }
}

if (CHECK){
  if (stale){ console.error(stale + " generated file(s) out of date: run node tools/build-guide-pages.js"); process.exit(1); }
  console.log("all " + expected.size + " generated files up to date");
} else {
  console.log(written + " of " + expected.size + " generated files written");
}
