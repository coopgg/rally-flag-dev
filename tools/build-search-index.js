#!/usr/bin/env node
/* ============================================================
   Writes assets/search-index.js for the site-wide quick search (nav.js:
   "/" or Ctrl/⌘+K, or the search button). The menu's own pages are added
   at runtime from nav.js; this file holds the content inside pages:

   - every raid and dungeon guide, and each encounter (#encounter-<slug>)
   - God Rolls weapons (god-rolls.html#weapon-<slug>)
   - builds (builds.html#build-<slug>)
   - armor sets (armor-set-bonuses.html?highlight=<slug>)
   - redeemable codes (codes.html)

   Entries are [title, kind, url, extra words to match]. The search loads it
   only when it's first opened. Re-run after changing any of those data
   files (or codes.html); --check exits 1 if the file is stale.
     node tools/build-search-index.js [--check]
   ============================================================ */
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "assets", "search-index.js");
const window = {};
for (const f of ["raids-data", "dungeons-data", "god-rolls-data", "builds-data", "sets-data"])
  new Function("window", fs.readFileSync(path.join(ROOT, "assets", f + ".js"), "utf8"))(window);

// Same anchor ids as raid-guide.html / dungeon-guide.html.
const slugify = name => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const guide = (kind, slug) => kind + "-" + slug + ".html";
const entries = [];
const add = (title, kind, url, words) => entries.push([title, kind, url, (words || "").replace(/\s+/g, " ").trim()]);

for (const [kind, label, list] of [["raid", "Raid", window.RaidsData.RAIDS], ["dungeon", "Dungeon", window.DungeonsData.DUNGEONS]]){
  for (const a of list){
    add(a.name, label + " guide", guide(kind, a.slug), kind);
    (a.encounters || []).forEach((e, i) => {
      if (!e.name) return;
      add(e.name, a.name, guide(kind, a.slug) + "#encounter-" + slugify(e.name), "encounter " + kind);
    });
  }
}
for (const w of window.GodRollsData.WEAPONS) add(w.name, "God Roll", "god-rolls.html#weapon-" + w.slug, "weapon god roll " + (w.raidSlug || w.dungeonSlug || "").replace(/-/g, " "));
for (const b of window.BuildsData.BUILDS)
  add(b.title, "Build", "builds.html#build-" + b.slug, ["build", b.class, b.subclass, b.exoticArmor && b.exoticArmor.name, b.exoticWeapon && b.exoticWeapon.name].filter(x => typeof x === "string").join(" "));
for (const s of window.ArmorSetsData.SETS) add(s.name, "Armor set", "armor-set-bonuses.html?highlight=" + s.slug, "armor set bonus " + (s.source || ""));
const codes = fs.readFileSync(path.join(ROOT, "codes.html"), "utf8").matchAll(/\{\s*code:"([A-Z0-9-]+)",\s*name:"([^"]+)"/g);
for (const [, code, name] of codes) add(name, "Code", "codes.html", "code redeem emblem " + code);

const body = "/* GENERATED by tools/build-search-index.js from the raid, dungeon, God Roll,\n" +
  "   build and armor set data and codes.html. Don't edit; re-run it.\n" +
  "   [title, kind, url, extra words] for the quick search in nav.js. */\n" +
  "window.RallyFlagSearchIndex = [\n" + entries.map(e => JSON.stringify(e)).join(",\n") + "\n];\n";

if (process.argv.includes("--check")){
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (now !== body){ console.error("assets/search-index.js is stale: run node tools/build-search-index.js"); process.exit(1); }
  console.log("search index is up to date (" + entries.length + " entries)");
} else {
  fs.writeFileSync(OUT, body);
  console.log(entries.length + " entries written to assets/search-index.js");
}
